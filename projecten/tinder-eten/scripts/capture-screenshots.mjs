import { spawn } from 'node:child_process'
import { mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { chromium } from 'playwright'

const root = resolve(import.meta.dirname, '..')
const output = join(root, 'screenshots')
const port = 4181
const baseUrl = `http://127.0.0.1:${port}`
const server = spawn(process.execPath, [join(root, 'node_modules/vite/bin/vite.js'), '--host', '127.0.0.1', '--port', String(port)], { cwd: root, stdio: 'ignore' })

async function waitForServer() {
  for (let attempt = 0; attempt < 50; attempt++) {
    try { if ((await fetch(baseUrl)).ok) return } catch { /* server is still starting */ }
    await new Promise((resolveWait) => setTimeout(resolveWait, 100))
  }
  throw new Error(`Screenshot server did not start at ${baseUrl}`)
}

async function prepare(page) {
  await page.addInitScript(() => localStorage.clear())
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(baseUrl)
  await page.evaluate(() => document.fonts.ready)
  await page.waitForFunction(() => [...document.images].every((image) => image.complete))
  await page.addStyleTag({ content: '*,*::before,*::after{animation:none!important;transition:none!important}' })
}

